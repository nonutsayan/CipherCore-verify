package com.ciphercore.verify.service;

import com.ciphercore.verify.model.AnomalyRecord;
import com.ciphercore.verify.model.Document;
import com.ciphercore.verify.model.EvidenceRecord;
import com.ciphercore.verify.model.enums.AnomalySeverity;
import com.ciphercore.verify.model.enums.AnomalyType;
import com.ciphercore.verify.repository.AnomalyRecordRepository;
import com.ciphercore.verify.repository.EvidenceRecordRepository;
import org.apache.pdfbox.Loader;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDDocumentInformation;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;

import java.io.File;
import java.text.SimpleDateFormat;
import java.util.*;

/**
 * Section 9: Suspicious Metadata Analysis Service
 * Inspects PDF / EXIF header properties, creation vs modification chronologies,
 * and detects unexpected image-manipulation software producers.
 */
@Service
public class MetadataAnalysisService {

    private static final Logger log = LoggerFactory.getLogger(MetadataAnalysisService.class);

    private static final List<String> GRAPHIC_EDITORS = List.of(
        "photoshop", "gimp", "canva", "coreldraw", "illustrator", "inkscape", "pdfill", "paint.net"
    );

    @Autowired
    private AnomalyRecordRepository anomalyRecordRepository;

    @Autowired
    private EvidenceRecordRepository evidenceRecordRepository;

    public record MetadataReport(
        String creationDate,
        String modificationDate,
        String producer,
        String creator,
        String title,
        String author,
        boolean isEncrypted,
        List<String> observations
    ) {}

    public MetadataReport analyzeMetadata(Document document, Long runId) {
        File diskFile = new File(document.getStoredPath());
        if (!diskFile.exists() || !"application/pdf".equalsIgnoreCase(document.getMimeType())) {
            return new MetadataReport("N/A", "N/A", "N/A", "N/A", "N/A", "N/A", false, List.of("Not a PDF file or file unavailable"));
        }

        List<String> observations = new ArrayList<>();
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss z");

        try (PDDocument pd = Loader.loadPDF(diskFile)) {
            PDDocumentInformation info = pd.getDocumentInformation();
            if (info == null) {
                observations.add("No PDF DocumentInformation dictionary found");
                return new MetadataReport("N/A", "N/A", "N/A", "N/A", "N/A", "N/A", pd.isEncrypted(), observations);
            }

            Calendar cCal = info.getCreationDate();
            Calendar mCal = info.getModificationDate();
            String cDateStr = cCal != null ? sdf.format(cCal.getTime()) : "Not Specified";
            String mDateStr = mCal != null ? sdf.format(mCal.getTime()) : "Not Specified";
            String producer = info.getProducer() != null ? info.getProducer() : "Unknown";
            String creator = info.getCreator() != null ? info.getCreator() : "Unknown";
            String title = info.getTitle() != null ? info.getTitle() : "";
            String author = info.getAuthor() != null ? info.getAuthor() : "";

            // 1. Check for graphic editing software in Producer / Creator
            String combinedSoftware = (producer + " " + creator).toLowerCase();
            for (String editor : GRAPHIC_EDITORS) {
                if (combinedSoftware.contains(editor)) {
                    String desc = String.format("Document metadata indicates generation via graphic editing tool: '%s' (Producer: %s, Creator: %s).",
                        editor.toUpperCase(), producer, creator);
                    observations.add(desc);

                    AnomalyRecord anomaly = new AnomalyRecord(
                        runId,
                        document.getId(),
                        document.getApplicationId(),
                        AnomalyType.METADATA_INCONSISTENCY,
                        AnomalySeverity.MEDIUM,
                        "Graphic Editing Software Detected in Metadata: " + editor.toUpperCase(),
                        desc,
                        "Official regulatory orders, certificates, and gazettes are typically generated by government publishing systems or standard office suites rather than graphic design software.",
                        "RULE_METADATA_GRAPHIC_EDITOR",
                        0.88,
                        "Conduct visual inspection for potential layer or text compositing. Note: Harmless cropping or compression can also inject editor tags."
                    );
                    anomalyRecordRepository.save(anomaly);

                    EvidenceRecord ev = new EvidenceRecord(
                        anomaly,
                        document.getId(),
                        "METADATA_OBSERVATION",
                        1,
                        "PDF.Producer / Creator",
                        "Producer: " + producer + " | Creator: " + creator,
                        "Official Institutional Document Expectation",
                        "Image-editing applications may have been used for legitimate compression or scanning. This is an indicator for review, not proof of tampering."
                    );
                    evidenceRecordRepository.save(ev);
                    break;
                }
            }

            // 2. Chronological check: ModDate prior to CreationDate
            if (cCal != null && mCal != null && mCal.before(cCal)) {
                String desc = String.format("Contradictory embedded timestamps: Modification Date (%s) precedes Creation Date (%s).", mDateStr, cDateStr);
                observations.add(desc);

                AnomalyRecord anomaly = new AnomalyRecord(
                    runId,
                    document.getId(),
                    document.getApplicationId(),
                    AnomalyType.METADATA_INCONSISTENCY,
                    AnomalySeverity.HIGH,
                    "Contradictory File Timestamps (Modification < Creation)",
                    desc,
                    "Modification date preceding creation date suggests clock manipulation, corrupted header reconstruction, or synthetic file generation.",
                    "RULE_METADATA_TIMESTAMP_INVERSION",
                    0.92,
                    "Inspect file source provenance and verify execution date against institutional archives."
                );
                anomalyRecordRepository.save(anomaly);

                EvidenceRecord ev = new EvidenceRecord(
                    anomaly,
                    document.getId(),
                    "METADATA_OBSERVATION",
                    1,
                    "CreationDate / ModDate",
                    "CreationDate: " + cDateStr + " | ModDate: " + mDateStr,
                    "Consistent Chronological Sequence",
                    "Timestamps can occasionally be altered by faulty system clocks or PDF rebuilders."
                );
                evidenceRecordRepository.save(ev);
            }

            return new MetadataReport(cDateStr, mDateStr, producer, creator, title, author, pd.isEncrypted(), observations);

        } catch (Exception e) {
            log.warn("Error reading PDF metadata for document {}: {}", document.getId(), e.getMessage());
            observations.add("Metadata parsing error: " + e.getMessage());
            return new MetadataReport("ERROR", "ERROR", "ERROR", "ERROR", "", "", false, observations);
        }
    }
}
